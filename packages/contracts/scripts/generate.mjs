// Generates TypeScript from the contract sources. Output in src/gen/ is committed;
// CI re-runs `pnpm generate` and fails if anything changed.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { compile } from "json-schema-to-typescript";

const root = join(import.meta.dirname, "..");
const gen = join(root, "src", "gen");
const banner = "// Generated by packages/contracts/scripts/generate.mjs. DO NOT EDIT.\n";
const run = (cmd, args) => execFileSync(cmd, args, { cwd: root, stdio: "inherit" });

rmSync(gen, { recursive: true, force: true });
mkdirSync(gen, { recursive: true });

// 1. engine.proto → src/gen/engine/v1/engine_pb.ts (protoc-gen-es, see buf.gen.yaml)
run("buf", ["generate"]);

// 2. OpenAPI → src/gen/lesson-player.ts (types for openapi-fetch)
run("openapi-typescript", ["openapi/lesson-player.yaml", "-o", "src/gen/lesson-player.ts"]);

// 3. JSON Schemas → TypeScript types + the schemas themselves as constants
const schemaFiles = [
  ["schemas", "item.schema.json"],
  ...readdirSync(join(root, "events"))
    .filter((f) => f.endsWith(".schema.json") && f !== "envelope.schema.json")
    .sort()
    .map((f) => ["events", f]),
];
let types = banner;
let consts = banner;
for (const [dir, file] of schemaFiles) {
  const schema = JSON.parse(readFileSync(join(root, dir, file), "utf8"));
  types += (await compile(schema, schema.title, { bannerComment: "", additionalProperties: false })) + "\n";
  const name = schema.title.charAt(0).toLowerCase() + schema.title.slice(1) + "Schema";
  consts += `export const ${name} = ${JSON.stringify(schema, null, 2)} as const;\n\n`;
}
writeFileSync(join(gen, "schemas.types.ts"), types);
writeFileSync(join(gen, "schemas.ts"), consts);
